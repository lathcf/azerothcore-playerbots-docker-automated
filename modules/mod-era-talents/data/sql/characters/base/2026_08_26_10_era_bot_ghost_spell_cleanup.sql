-- mod-era-talents: purge orphaned character_spell rows (specMask = 0).
--
-- A specMask of 0 means the spell is active in NO talent spec — dead data the client can
-- never use (HasSpell() is false), but Player::_LoadSpells still loads it into the spell
-- map, where mod-playerbots' name-based resolution (SpellIdValue) saw it WITHOUT a spec
-- check and let it shadow a same-name era clone (live 2026-08-26: a Vanilla-band shadow
-- priest bot resolved "vampiric embrace" to its ghost WotLK 15286 row instead of the era
-- 921152 it actually knows -> every VE cast refused). The ghosts are the WotLK talent
-- actives (Preparation, Hemorrhage, Shadowstep, ...) left behind when era rebuilds/respecs
-- stripped bots' native talents: 91,932 rows across 3,384 characters on production.
--
-- Patch 0021's SpellIdValue spec-check makes ghosts harmless at runtime; this removes the
-- existing rows for good (safe for real players too — a specMask-0 row is unusable by
-- definition). Idempotent.
DELETE FROM `character_spell` WHERE `specMask` = 0;
