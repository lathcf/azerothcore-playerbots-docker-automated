CREATE TABLE IF NOT EXISTS `era_character_talent` (
  `guid` INT UNSIGNED NOT NULL,
  `eraId` TINYINT UNSIGNED NOT NULL,
  `talentId` INT UNSIGNED NOT NULL,
  `rank` TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (`guid`,`eraId`,`talentId`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `era_talent_char_state` (
  `guid` INT UNSIGNED NOT NULL,
  `lastEra` TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (`guid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
