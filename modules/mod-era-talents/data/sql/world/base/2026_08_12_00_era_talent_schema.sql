CREATE TABLE IF NOT EXISTS `era_talent` (
  `id` INT UNSIGNED NOT NULL,
  `eraId` TINYINT UNSIGNED NOT NULL,
  `classId` TINYINT UNSIGNED NOT NULL,
  `tab` TINYINT UNSIGNED NOT NULL,
  `tierRow` TINYINT UNSIGNED NOT NULL,
  `col` TINYINT UNSIGNED NOT NULL,
  `maxRank` TINYINT UNSIGNED NOT NULL,
  `prereqTalentId` INT UNSIGNED NOT NULL DEFAULT 0,
  `prereqPoints` TINYINT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `era_class` (`eraId`,`classId`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `era_talent_rank` (
  `talentId` INT UNSIGNED NOT NULL,
  `rank` TINYINT UNSIGNED NOT NULL,
  `grantedSpellId` INT UNSIGNED NOT NULL,
  PRIMARY KEY (`talentId`,`rank`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
