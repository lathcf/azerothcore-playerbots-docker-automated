#!/usr/bin/env bash
# regen-naxx40-patch.sh — re-cut patches/0022-playerbot-naxx40.patch from the fork working tree
# at azerothcore-wotlk/modules/mod-playerbots.
#
# 0022 has five parts under src/Ai/Raid/Naxx/ (plus Patchwerk's one-line pre-cast hook in src/Bot/PlayerbotAI.cpp):
#  - Instructor Razuvious finds the Death Knight Understudies by creature entry (16803 WotLK,
#    351084 mod-individual-progression Naxx40) instead of by name. IP's Naxx40 student is named
#    "Deathknight Understudy", so the name match never found it: priests never mind-controlled and
#    tanks never picked one up. Also skips already-charmed students and casts Blood Strike only from
#    the WotLK student (the Naxx40 one has no such spell).
#  - The Naxx40 Four Horsemen strategy (Naxx40Horsemen* rules/stations/trigger/actions; Naxx40HorsemenStations.h is GENERATED by
#    tools/naxx40-horsemen-stations.py from the in-game probe log), since IP's
#    boss_four_horsemen_40 never walks the horsemen to their corners.
#  - The Naxx40 Loatheb strategy (Naxx40Loatheb* rules/trigger/actions): heal rotation under IP's
#    Corrupted Mind lockout (one heal per healer per 20 s), DPS killing the spores that walk to them, and
#    consumables (bandages/potions/healthstones) supplied under the `raid` bot cheat.
#  - The Naxx40 Anub'Rekhan raid spread (Naxx40AnubRules.h, Naxx40Anub.{h,cpp}, Action/NaxxActions_Anub40.cpp and
#    the `naxx40 anub spread` trigger/action/multiplier wiring): non-tanks on an arc around him (melee on two flanks
#    outside Locust Swarm) so one Impale cone hits a few bots, not the clump upstream's swarm phase makes.
#  - The Naxx40 Patchwerk soaker strategy (Naxx40PatchwerkRules.h, Naxx40Patchwerk.{h,cpp}, Action/NaxxActions_Patchwerk40.cpp and
#    the `naxx40 patchwerk` trigger/action/multiplier wiring): Hateful Strike soaked by role tanks in threat order,
#    healers split between the soakers and the raid, DPS capped under the soaker threat.
#
# BASELINE-AWARE for src/Bot/PlayerbotAI.cpp (since the 2026-11-01 Patchwerk pull-1 round: soaker healers
# pre-cast, so UpdateAI's full-health heal interrupt asks Naxx40Patchwerk::KeepPrecastHeal; pull 2 added the
# last-moment Naxx40Patchwerk::CancelPrecastHeal branch right after it). Patch order on that
# file: overlay 0003, 0004, 0014, 0016 (EARLIER) -> 0022 (ours) -> mod-era-talents
# patches/playerbots/02-era-ai.patch (LATER, applied by its apply-patches.sh). Patches are applied UNSTAGED, so
# a naive `git diff` would embed every one of their hunks. We rebuild an index baseline = pristine + the
# earlier four (the regen-aq40-patch.sh recipe), strip the LATER era hunk from the working copy by
# reverse-apply, diff, and restore the working copy + index from a trap. Everything under src/Ai/Raid/Naxx/
# is still a plain scoped diff: no other overlay or mod-era-talents patch touches that tree (checked
# 2026-10-26). The prefix flags make the patch apply from the fork root, matching how setup.sh's
# apply_patches runs `git -C "$AC_DIR" apply`.
#
# LITERAL PATHS ONLY on every git line. zsh does not word-split an unquoted $var, so a
# `for f in $FILES` loop would cut an empty patch (this trap has bitten the WG/publish recipes).
#
# Re-runnable; leaves the fork tree and index exactly as found.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
AC="$ROOT/azerothcore-wotlk"
PB="$AC/modules/mod-playerbots"
OUT="$ROOT/patches/0022-playerbot-naxx40.patch"
P0003="$ROOT/patches/0003-playerbot-wintergrasp.patch"
P0004="$ROOT/patches/0004-playerbot-wintergrasp-siege.patch"
P0014="$ROOT/patches/0014-playerbot-sunwell.patch"
P0016="$ROOT/patches/0016-playerbot-aq40.patch"
ERA_AI="$AC/modules/mod-era-talents/patches/playerbots/02-era-ai.patch"

[[ -d "$PB/.git" ]] || { echo "ERROR: $PB is not a git clone (run setup.sh first)" >&2; exit 1; }
for p in "$P0003" "$P0004" "$P0014" "$P0016"; do
  [[ -f "$p" ]] || { echo "ERROR: baseline patch $(basename "$p") missing" >&2; exit 1; }
done
for token in KeepPrecastHeal CancelPrecastHeal; do
  grep -q "$token" "$PB/src/Bot/PlayerbotAI.cpp" \
    || { echo "ERROR: PlayerbotAI.cpp has no $token — 0022 Patchwerk pre-cast edit not in the fork worktree" >&2; exit 1; }
done
[[ -f "$PB/src/Ai/Raid/Naxx/Naxx40HorsemenRules.h" ]] \
  || { echo "ERROR: Naxx40HorsemenRules.h missing — 0022 Horsemen edits not present in the fork worktree" >&2; exit 1; }
[[ -f "$PB/src/Ai/Raid/Naxx/Naxx40HorsemenStations.h" ]] \
  || { echo "ERROR: Naxx40HorsemenStations.h missing — run tools/naxx40-horsemen-stations.py pick (or restore the provisional header)" >&2; exit 1; }
[[ -f "$PB/src/Ai/Raid/Naxx/Naxx40LoathebRules.h" ]] \
  || { echo "ERROR: Naxx40LoathebRules.h missing — 0022 Loatheb edits not present in the fork worktree" >&2; exit 1; }
[[ -f "$PB/src/Ai/Raid/Naxx/Naxx40AnubRules.h" ]] \
  || { echo "ERROR: Naxx40AnubRules.h missing — 0022 Anub'Rekhan edits not present in the fork worktree" >&2; exit 1; }
[[ -f "$PB/src/Ai/Raid/Naxx/Naxx40PatchwerkRules.h" ]] \
  || { echo "ERROR: Naxx40PatchwerkRules.h missing — 0022 Patchwerk edits not present in the fork worktree" >&2; exit 1; }

TMP="$(mktemp -d)"
restore() {
  [[ -f "$TMP/PlayerbotAI.cpp" ]] && cp "$TMP/PlayerbotAI.cpp" "$PB/src/Bot/PlayerbotAI.cpp"
  # Unstage the baseline and the intent-to-add entries, so the fork index is left exactly as found.
  git -C "$PB" reset -q -- src/Bot/PlayerbotAI.cpp src/Ai/Raid/Naxx 2>/dev/null || true
  rm -rf "$TMP"
}
trap restore EXIT

# PlayerbotAI.cpp: index baseline = pristine + the EARLIER patches on it (0003, 0004, 0014, 0016).
cp "$PB/src/Bot/PlayerbotAI.cpp" "$TMP/PlayerbotAI.cpp"
git -C "$PB" checkout -- src/Bot/PlayerbotAI.cpp
git -C "$AC" apply --include=modules/mod-playerbots/src/Bot/PlayerbotAI.cpp "$P0003"
git -C "$AC" apply --include=modules/mod-playerbots/src/Bot/PlayerbotAI.cpp "$P0004"
git -C "$AC" apply --include=modules/mod-playerbots/src/Bot/PlayerbotAI.cpp "$P0014"
git -C "$AC" apply --include=modules/mod-playerbots/src/Bot/PlayerbotAI.cpp "$P0016"
git -C "$PB" add -- src/Bot/PlayerbotAI.cpp
cp "$TMP/PlayerbotAI.cpp" "$PB/src/Bot/PlayerbotAI.cpp"
# The LATER era-talents 02-era-ai.patch is in the working tree but in no baseline: strip it from the
# working copy by reverse-apply, or 0022 absorbs its hunk. The EXIT trap restores the real file.
if [[ -f "$ERA_AI" ]]; then
  if git -C "$AC" apply -R --check --include=modules/mod-playerbots/src/Bot/PlayerbotAI.cpp "$ERA_AI" 2>/dev/null; then
    git -C "$AC" apply -R --include=modules/mod-playerbots/src/Bot/PlayerbotAI.cpp "$ERA_AI"
  else
    echo "WARN: era 02-era-ai.patch does not reverse-apply on PlayerbotAI.cpp — contamination canary decides" >&2
  fi
fi

# The new files ride along via intent-to-add so they appear in the diff (the trap unstages them).
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40HorsemenRules.h
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40HorsemenStations.h
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40Horsemen.h
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40Horsemen.cpp
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Action/NaxxActions_Horsemen40.cpp
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40LoathebRules.h
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40Loatheb.h
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40Loatheb.cpp
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Action/NaxxActions_Loatheb40.cpp
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40AnubRules.h
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40Anub.h
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40Anub.cpp
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Action/NaxxActions_Anub40.cpp
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40PatchwerkRules.h
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40Patchwerk.h
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Naxx40Patchwerk.cpp
git -C "$PB" add -N -- src/Ai/Raid/Naxx/Action/NaxxActions_Patchwerk40.cpp
git -C "$PB" diff \
  --src-prefix=a/modules/mod-playerbots/ \
  --dst-prefix=b/modules/mod-playerbots/ \
  -- src/Ai/Raid/Naxx src/Bot/PlayerbotAI.cpp \
  > "$OUT"
# Put the real PlayerbotAI.cpp (era hunk included) and the index back NOW, so the reverse-apply gate below
# checks the patch against the worktree exactly as it is built.
restore
trap - EXIT

# Gates. A bad patch here plus a fork reset would orphan the work.
[[ -s "$OUT" ]] || { echo "GATE FAIL: generated patch is empty" >&2; exit 1; }
if grep '^diff --git' "$OUT" | grep -v ' a/modules/mod-playerbots/src/Ai/Raid/Naxx/' \
     | grep -v ' a/modules/mod-playerbots/src/Bot/PlayerbotAI.cpp '; then
  echo "GATE FAIL: patch touches files outside src/Ai/Raid/Naxx/ + src/Bot/PlayerbotAI.cpp (listed above)" >&2
  rm -f "$OUT"; exit 1
fi
# The PlayerbotAI.cpp hunk must carry the pre-cast hook and NOTHING from the other patches on that file.
# Canaries scan CHANGED lines only (grepping context lines makes a gate that can never fail).
PBAI_HUNKS="$(awk '/^diff --git/ { keep = ($0 ~ /src\/Bot\/PlayerbotAI\.cpp/) } keep' "$OUT")"
for token in KeepPrecastHeal CancelPrecastHeal; do
  printf '%s\n' "$PBAI_HUNKS" | grep -E '^[+-]' | grep -v '^[+-][+-][+-]' | grep -q "$token" \
    || { echo "GATE FAIL: PlayerbotAI.cpp hunk missing $token" >&2; rm -f "$OUT"; exit 1; }
done
for banned in "HuhuranKeepWyvernSting" "Aq40Helpers" "case 531" "PerfMonitorOperation" "perfMonEnabled" \
              "EraTalentBots" "SMSG_BATTLEFIELD_MGR_ENTRY_INVITE" "isBFGroup" "SWP" "sunwell" "case 580"; do
  if printf '%s\n' "$PBAI_HUNKS" | grep -E '^[+-]' | grep -v '^[+-][+-][+-]' | grep -q -- "$banned"; then
    echo "GATE FAIL: 0022 PlayerbotAI.cpp hunk contains '$banned' — another patch's hunks leaked in" >&2
    rm -f "$OUT"; exit 1
  fi
done
grep -q "NPC_UNDERSTUDY_40" "$OUT" || { echo "GATE FAIL: patch does not mention NPC_UNDERSTUDY_40" >&2; exit 1; }
grep -q "Naxx40HorsemenRules" "$OUT" || { echo "GATE FAIL: patch missing Naxx40HorsemenRules.h" >&2; exit 1; }
grep -q "Naxx40HorsemenStations" "$OUT" || { echo "GATE FAIL: patch missing Naxx40HorsemenStations.h" >&2; exit 1; }
grep -q "Naxx40LoathebRules" "$OUT" || { echo "GATE FAIL: patch missing Naxx40LoathebRules.h" >&2; exit 1; }
grep -q "Naxx40AnubRules" "$OUT" || { echo "GATE FAIL: patch missing Naxx40AnubRules.h" >&2; exit 1; }
grep -q "Naxx40PatchwerkRules" "$OUT" || { echo "GATE FAIL: patch missing Naxx40PatchwerkRules.h" >&2; exit 1; }
grep -q "Naxx40AnubSpreadAction::Execute" "$OUT" \
  || { echo "GATE FAIL: patch missing Naxx40AnubSpreadAction::Execute (Action/NaxxActions_Anub40.cpp)" >&2; exit 1; }
if grep -q "NX40HM-DEBUG" "$OUT"; then
  echo "GATE FAIL: patch still contains temporary [NX40HM-DEBUG] logging" >&2; exit 1
fi
# The worktree must contain exactly this patch: reverse-applying it must be clean.
git -C "$AC" apply --reverse --check "$OUT" \
  || { echo "GATE FAIL: patch does not reverse-apply against the fork worktree" >&2; exit 1; }

echo "OK: wrote $OUT ($(wc -l < "$OUT") lines)"
git -C "$AC" apply --stat "$OUT" | sed 's/^/    /'
