def test_band_ownership_flags_out_of_band_chain_root(tmp_path, monkeypatch):
    sql = SQL_FIXTURE + "INSERT INTO `spell_ranks` (`first_spell_id`,`spell_id`,`rank`) VALUES\n  (12345, 12345, 1),\n  (12345, 946270, 2);\n"
