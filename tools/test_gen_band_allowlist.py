_spec = _ilu.spec_from_file_location("gen_band_allowlist", "tools/gen_band_allowlist.py")
GB = _ilu.module_from_spec(_spec); _spec.loader.exec_module(GB)

GOOD = """\
entries:
  - ids: [932749]
    eras: [vanilla]
    classes: [paladin]
    kind: marker
    note: seal-training marker
  - range: [946000, 946026]
    eras: [tbc]
    classes: [paladin]
    kind: trainer
    note: TBC seal chains below SoC r1
  - ids: [946261, 946262, 946263]
    eras: [tbc]
    classes: [druid]
    kind: partner
    node: {tbc: 20141}
    note: Mangle (Cat) partner chain
  - ids: [932513]
    eras: [vanilla, tbc]
    classes: [druid]
    kind: level-grant
    note: Enrage clone
stranded: [920040, 921745]
"""

def _write(tmp_path, text):
    p = tmp_path / "band-allowlist.yaml"; p.write_text(text); return p

def test_load_good(tmp_path):
    al = GB.load_allowlist(_write(tmp_path, GOOD))
    assert len(al.entries) == 4 and al.stranded == [920040, 921745]
    e = al.entries[2]
    assert (e.lo, e.hi) == (946261, 946263)
    assert e.era_mask == 0b010 and e.class_mask == (1 << 11)
    assert e.node_by_era == [0, 20141, 0]
    assert al.entries[3].era_mask == 0b011

def test_emit_header_shape(tmp_path):
    al = GB.load_allowlist(_write(tmp_path, GOOD))
    h = GB.emit_header(al)
    assert h.startswith("// GENERATED by tools/gen_band_allowlist.py")
    assert "DO NOT EDIT" in h
    assert 'inline constexpr char const* kEraBandAllowlistHash = "' in h
    assert "{ 946261, 946263, 0x2, 0x800, { 0, 20141, 0 }, \"Mangle (Cat) partner chain\" }," in h
    assert "{ 932513, 932513, 0x3, 0x800, { 0, 0, 0 }, \"Enrage clone\" }," in h
    assert "inline constexpr size_t kEraBandAllowlistCount = 4;" in h

def test_hash_tracks_yaml_bytes(tmp_path):
    a = GB.emit_header(GB.load_allowlist(_write(tmp_path, GOOD)))
    b = GB.emit_header(GB.load_allowlist(_write(tmp_path, GOOD.replace("Enrage clone", "Enrage"))))
    assert GB.HASH_RE.search(a).group(1) != GB.HASH_RE.search(b).group(1)

@pytest.mark.parametrize("bad,msg", [
    (GOOD.replace("eras: [vanilla]\n    classes: [paladin]\n    kind: marker", "eras: [wrath]\n    classes: [paladin]\n    kind: marker"), "unknown era"),
    (GOOD.replace("classes: [paladin]\n    kind: marker", "classes: [pally]\n    kind: marker"), "unknown class"),
    (GOOD.replace("  - ids: [932749]\n", "  - ids: [932749]\n    range: [1, 2]\n"), "both ids and range"),
    (GOOD.replace("range: [946000, 946026]", "range: [946026, 946000]"), "range hi < lo"),
    (GOOD.replace("ids: [932749]", "ids: [12345]"), "outside the band"),
    (GOOD.replace("node: {tbc: 20141}", "node: {vanilla: 20141}"), "node for an unlisted era"),
    (GOOD.replace("kind: marker", "kind: thing"), "unknown kind"),
    (GOOD.replace("    note: seal-training marker\n", ""), "note"),
    (GOOD.replace("stranded: [920040, 921745]", "stranded: [920040, 932749]"), "stranded id 932749 is allowlisted"),
])
def test_rejects(tmp_path, bad, msg):
    with pytest.raises(GB.AllowlistError) as ei:
        GB.load_allowlist(_write(tmp_path, bad))
    assert msg in str(ei.value)

def test_cli_writes_header(tmp_path):
    y = _write(tmp_path, GOOD); out = tmp_path / "EraBandAllowlist.gen.h"
    r = subprocess.run([sys.executable, "tools/gen_band_allowlist.py", str(y), "-o", str(out)],
                       capture_output=True, text=True, cwd=os.getcwd())
    assert r.returncode == 0, r.stderr
    assert out.read_text().count("{ 9") == 4

